import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import * as Firebird from 'node-firebird'
import type { Options, SupportedCharacterSet } from 'node-firebird'

interface FirebirdTableRow {
  table_name: string
}

interface FirebirdColumnRow {
  table_name: string
  column_name: string
  field_position: number
  field_type: number
  field_subtype: number | null
  field_scale: number | null
  null_flag: number
}

const typeSchemas: Readonly<Record<number, string>> = {
  7: 'smallIntSchema',
  8: 'integerSchema',
  10: 'numberSchema',
  12: 'dateSchema',
  13: 'dateSchema',
  14: 'stringSchema',
  16: 'int64Schema',
  27: 'numberSchema',
  35: 'dateSchema',
  37: 'stringSchema',
  261: 'blobSchema',
}

const supportedCharsets = [
  'NONE',
  'CP943C',
  'DOS737',
  'DOS775',
  'DOS858',
  'DOS862',
  'DOS864',
  'DOS866',
  'DOS869',
  'GB18030',
  'GBK',
  'ISO8859_1',
  'ISO8859_2',
  'ISO8859_3',
  'ISO8859_4',
  'ISO8859_5',
  'ISO8859_6',
  'ISO8859_7',
  'ISO8859_8',
  'ISO8859_9',
  'ISO8859_13',
  'KOI8R',
  'KOI8U',
  'TIS620',
  'UTF8',
  'WIN1251',
  'WIN1252',
  'WIN1253',
  'WIN1254',
  'WIN1255',
  'WIN1256',
  'WIN1257',
  'WIN1258',
  'WIN_1258',
] as const satisfies readonly SupportedCharacterSet[]

function getConnectionOptions(): Options {
  const requiredVariables = [
    'FIREBIRD_HOST',
    'FIREBIRD_DATABASE',
    'FIREBIRD_USER',
    'FIREBIRD_PASSWORD',
  ] as const
  const missingVariables = requiredVariables.filter((name) => !process.env[name])

  if (missingVariables.length) {
    throw new Error(`Missing Firebird configuration: ${missingVariables.join(', ')}`)
  }

  const port = Number(process.env.FIREBIRD_PORT || 3050)
  if (!Number.isInteger(port) || port < 1 || port > 65535) {
    throw new Error('FIREBIRD_PORT must be an integer between 1 and 65535.')
  }

  const charset = process.env.FIREBIRD_CHARSET || 'UTF8'
  const encoding = supportedCharsets.find((supportedCharset) => supportedCharset === charset)
  if (!encoding) {
    throw new Error('FIREBIRD_CHARSET must be supported by node-firebird.')
  }

  return {
    host: process.env.FIREBIRD_HOST,
    port,
    database: process.env.FIREBIRD_DATABASE,
    user: process.env.FIREBIRD_USER,
    password: process.env.FIREBIRD_PASSWORD,
    role: process.env.FIREBIRD_ROLE || undefined,
    encoding,
    lowercase_keys: true,
    numericMode: 'string',
  }
}

function getSchemaName(column: FirebirdColumnRow): string {
  if ([7, 8, 16].includes(column.field_type) && column.field_scale) {
    return 'decimalSchema'
  }

  if (column.field_type === 16) {
    return 'int64Schema'
  }

  const schemaName = typeSchemas[column.field_type]
  if (!schemaName) {
    throw new Error(
      `Unsupported Firebird field type ${column.field_type} in ${column.table_name}.${column.column_name}.`,
    )
  }

  return schemaName
}

function formatPropertyName(name: string): string {
  return /^[A-Za-z_$][\w$]*$/.test(name) ? name : JSON.stringify(name)
}

function createSchemaSource(
  tables: readonly FirebirdTableRow[],
  columns: readonly FirebirdColumnRow[],
): string {
  const columnsByTable = new Map<string, FirebirdColumnRow[]>()
  for (const column of columns) {
    const tableColumns = columnsByTable.get(column.table_name) ?? []
    tableColumns.push(column)
    columnsByTable.set(column.table_name, tableColumns)
  }

  const tableSchemas = tables.map(({ table_name }) => {
    const tableColumns = columnsByTable.get(table_name)
    if (!tableColumns?.length) {
      throw new Error(`Firebird table ${table_name} has no column metadata.`)
    }

    const fields = tableColumns
      .sort((left, right) => left.field_position - right.field_position)
      .map((column) => {
        const schemaName = getSchemaName(column)
        const nullable = column.null_flag !== 1 ? '.nullable()' : ''
        return `    ${formatPropertyName(column.column_name)}: ${schemaName}${nullable},`
      })

    return `  ${formatPropertyName(table_name)}: z.object({\n${fields.join('\n')}\n  }),`
  })

  return `// Generated by scripts/generate-firebird-schemas.ts. Do not edit by hand.
import { z } from 'zod'

const numberSchema = z.number().finite()
const smallIntSchema = z.number().int().min(-32768).max(32767)
const integerSchema = z.number().int().min(-2147483648).max(2147483647)
const stringSchema = z.string()
const dateSchema = z.date()
const int64Schema = z.union([z.number().int(), z.string().regex(/^-?\\d+$/)])
const decimalSchema = z.union([z.number().finite(), z.string().regex(/^-?\\d+(?:\\.\\d+)?$/)])
const blobSchema = z.union([z.string(), z.instanceof(Uint8Array)])

export const firebirdTableSchemas = {
${tableSchemas.join('\n')}
}

export type FirebirdTableName = keyof typeof firebirdTableSchemas
export type FirebirdTableRow<TableName extends FirebirdTableName> = z.output<
  (typeof firebirdTableSchemas)[TableName]
>
`
}

async function main() {
  const database = await Firebird.attachAsync(getConnectionOptions())

  try {
    const tables = await database.queryAsync<FirebirdTableRow>(`
      SELECT TRIM(r.RDB$RELATION_NAME) AS table_name
      FROM RDB$RELATIONS r
      WHERE COALESCE(r.RDB$SYSTEM_FLAG, 0) = 0
        AND r.RDB$VIEW_BLR IS NULL
      ORDER BY r.RDB$RELATION_NAME
    `)
    const columns = await database.queryAsync<FirebirdColumnRow>(`
      SELECT
        TRIM(rf.RDB$RELATION_NAME) AS table_name,
        TRIM(rf.RDB$FIELD_NAME) AS column_name,
        rf.RDB$FIELD_POSITION AS field_position,
        f.RDB$FIELD_TYPE AS field_type,
        f.RDB$FIELD_SUB_TYPE AS field_subtype,
        f.RDB$FIELD_SCALE AS field_scale,
        COALESCE(rf.RDB$NULL_FLAG, f.RDB$NULL_FLAG, 0) AS null_flag
      FROM RDB$RELATION_FIELDS rf
      JOIN RDB$RELATIONS r ON r.RDB$RELATION_NAME = rf.RDB$RELATION_NAME
      JOIN RDB$FIELDS f ON f.RDB$FIELD_NAME = rf.RDB$FIELD_SOURCE
      WHERE COALESCE(r.RDB$SYSTEM_FLAG, 0) = 0
        AND r.RDB$VIEW_BLR IS NULL
      ORDER BY rf.RDB$RELATION_NAME, rf.RDB$FIELD_POSITION
    `)

    if (!tables.length || !columns.length) {
      throw new Error('The Firebird database returned no user table schema metadata.')
    }

    const schemaPath = fileURLToPath(
      new URL('../shared/schemas/firebird.schema.ts', import.meta.url),
    )
    await writeFile(schemaPath, createSchemaSource(tables, columns), 'utf8')
    process.stdout.write(`Generated Zod schemas for ${tables.length} Firebird tables.\n`)
  } finally {
    await database.detachAsync()
  }
}

await main()
